    private MvcResult createSession(int questionCount) throws Exception {
        String payload = """
                {
                    "mode": "QUIZ",
                    "trackId": %d,
                    "questionCount": %d,
                    "difficulty": "MIXED"
                }
                """.formatted(JAVA_BACKEND_TRACK_ID, questionCount);

        return mockMvc.perform(post("/api/v1/sessions")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(payload))
                .andExpect(status().isCreated())
                .andReturn();
    }

    private DocumentContext parse(MvcResult result) throws Exception {
        return JsonPath.parse(result.getResponse().getContentAsString());
    }

    private long extractLong(MvcResult result, String path) throws Exception {
        return ((Number) parse(result).read(path)).longValue();
    }

