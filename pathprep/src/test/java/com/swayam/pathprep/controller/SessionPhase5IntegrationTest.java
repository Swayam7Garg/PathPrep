        Question q2 = questionRepository.findWithDetailsById(q2Id).orElseThrow();
        long q2Opt = q2.getOptions().stream().filter(QuestionOption::isCorrect).findFirst().orElseThrow().getId();

        // Answer Q2 (last question)
